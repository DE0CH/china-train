// Regenerate lib/station-snapshot.ts from 12306's station_name.js (run when stations are added):
//   node scripts/update-stations.mjs
// api/query.ts uses the live list when 12306 is reachable directly and falls back to this snapshot
// (rather than spending ~165 KB of proxy traffic on it) when the instance's IP is blocked.
import { writeFileSync } from "node:fs";
const js = await (await fetch("https://kyfw.12306.cn/otn/resources/js/framework/station_name.js")).text();
const pairs = [...js.matchAll(/@[a-z0-9]*\|([^|]+)\|([A-Z]{3})\|/g)].map((m) => `${m[1].replace(/\s+/g, "")}|${m[2]}`);
if (pairs.length < 1000) throw new Error(`only ${pairs.length} stations parsed`);
writeFileSync(new URL("../lib/station-snapshot.ts", import.meta.url),
  `// Generated by scripts/update-stations.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit.\n` +
  `// "name|TELECODE" pairs from 12306's station_name.js, joined with "@".\n` +
  `export const STATION_SNAPSHOT = ${JSON.stringify(pairs.join("@"))};\n`);
console.log(`${pairs.length} stations`);
